feat(tools): 新增 check_quotes.py —— 查引语是不是编的

起因：某引擎首版给受访者补了一句没说过的话，checker 给了满分。
checker 不懂语义、lint 只查格式，「有没有编造」这条一直靠人自觉。

判据：引语可以删减，不能改字
- 素材子串 → 逐字
- 素材子序列（只删字）→ 省略，算有出处
- 需换字才对上 → 非逐字
- 对不上 → 疑似自造

不用「相似度≥0.85 算逐字」：那样「半小时→两小时」相似度 0.96 会被漏掉，
而它恰恰是最该抓的篡改。

只核对被安到具体人物头上的引语（人名或第三人称+说话动词同句）。
作者用「」命名概念（「出片」「能不能说」）不算引语——这条是踩了
三轮误报才定下来的：跨段窗口、段落窗口、句级窗口逐级收窄。

实测 20 篇：疑似自造 0，非逐字 4。注入三种篡改（编造整句/改数字/改词）
全部命中。